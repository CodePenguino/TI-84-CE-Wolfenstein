.macro texmac from=1, to=60
	exx
	add hl,bc
	ld  e,h
	ld  a,(de)
	exx

	ld (hl),a
	add hl,de
	ld (hl),a
	add hl,de
	ld (hl),a
	add hl,de

	.if \to-\from
	texmac "(\from+1)",\to
	.endif
.endm

.macro colmac from=1, to=90
	ld (hl),a
	add hl,de

	.if \to-\from
	colmac "(\from+1)",\to
	.endif
.endm

